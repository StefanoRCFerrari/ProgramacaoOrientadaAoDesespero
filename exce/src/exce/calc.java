package exce;


public class calc {

   float n1, n2;
    
    public calc(float n1, float n2){
        
        this.n1 = n1;
        this.n2 = n2;
    }
    
    public float soma(){
        return this.n1+this.n2;
    }
    
    public float divide(){
        return this.n1/this.n2;
    }
    
    
}
